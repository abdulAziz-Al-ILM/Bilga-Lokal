#!/usr/bin/env python3
"""Keep native widget/launcher labels aligned with Bilga's 43 JSON catalogs."""
import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
KEYS = {
    'nw_widget': 'widgetNotes', 'nw_notes': 'notes', 'nw_new_note': 'newNote',
    'nw_search': 'search', 'nw_settings': 'profile', 'nw_hidden': 'widgetHidden',
    'nw_empty': 'empty',
}

def document(catalog):
    rows = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tool/generate_notes_widget_strings.py -->', '<resources>']
    for name, key in KEYS.items():
        text = escape(catalog[key].replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"'))
        rows.append(f'    <string name="{name}" formatted="false">{text}</string>')
    return '\n'.join(rows + ['</resources>', ''])

if __name__ == '__main__':
    for path in sorted((ROOT / 'assets/i18n').glob('*.json')):
        catalog = json.loads(path.read_text())
        for qualifier in [f"values-{'iw' if path.stem == 'he' else path.stem}"] + (['values'] if path.stem == 'en' else []):
            folder = ROOT / 'android/app/src/main/res' / qualifier
            folder.mkdir(exist_ok=True)
            (folder / 'notes_widget_strings.xml').write_text(document(catalog))
